import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { runGuard } from '../packages/guard/src/runGuard.mjs';
import { renderRoleBasedHtml, validatePreviewForRendering } from '../packages/guard/src/presentation/role_based_html_report.mjs';

const source = await runGuard({argv:['report','single-agent','--pack','examples/single-agent-governance-pack/hr-self-service-agent','--preview','--json']});
assert.equal(source.exitCode,0,'existing report path must remain unchanged');
const bytes=Buffer.from(source.stdout,'utf8');
const r=JSON.parse(source.stdout);
validatePreviewForRendering(r);
const html1=renderRoleBasedHtml(r,bytes);
const html2=renderRoleBasedHtml(r,bytes);
assert.equal(html1,html2,'identical input bytes must produce byte-identical HTML');
assert.match(html1,/<html lang="en">/);
assert.match(html1,/Business owner/);
assert.match(html1,/Technical reviewer/);
assert.match(html1,/Governance \/ risk reviewer/);
assert.match(html1,/No operational authority/);
assert.match(html1,/Source report timestamp/);
assert.match(html1,/Source field: <code>\/authority_summary<\/code>/);
assert.match(html1,/2026-05-11T09:00:00Z/);
assert.match(html1,/ready_for_review/);
assert.ok(!html1.includes('<script'),'no executable JavaScript in HTML output');
assert.ok(!html1.includes('https://cdn.'),'offline presentation only');
assert.ok(html1.includes(crypto.createHash('sha256').update(bytes).digest('hex')),'byte digest must be embedded');
// The original source JSON must survive exact text display as escaped material.
assert.ok(html1.includes('&quot;object_type&quot;'));
const bad={...r, non_enforcement_boundary:{...r.non_enforcement_boundary, approval_granted:true}};
assert.throws(()=>validatePreviewForRendering(bad),/Non-enforcement contract mismatch/);
const malicious={...r,agent_identity:{...r.agent_identity,agent_label:'<img src=x onerror=alert(1)>'},authority_summary:'</pre><script>alert(1)</script>'};
const malwareBytes=Buffer.from(JSON.stringify(malicious),'utf8');
const safe=renderRoleBasedHtml(malicious,malwareBytes);
assert.ok(!safe.includes('<img src=x onerror=alert(1)>'));
assert.ok(!safe.includes('<script>alert(1)</script>'));
assert.ok(safe.includes('&lt;script&gt;alert(1)&lt;/script&gt;'));
const wrongContract={...r,report_mode:'final'};
assert.throws(()=>validatePreviewForRendering(wrongContract),/Unsupported report contract/);
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'mf-guard-report-render-v0.1-'));
try {
  const input=path.join(tmp,'input.json');const out=path.join(tmp,'readable.html');
  fs.writeFileSync(input,bytes);
  const normal=await runGuard({argv:['report','render','--input',input,'--out',out,'--format','html']});
  assert.equal(normal.exitCode,0,normal.stderr);
  assert.equal(fs.readFileSync(out,'utf8'),html1);
  assert.deepEqual(fs.readFileSync(input),bytes,'source bytes must remain unchanged');
  assert.equal((await runGuard({argv:['report','render','--input',input,'--out',out,'--format','html']})).exitCode,4,'cannot overwrite output');
  assert.equal((await runGuard({argv:['report','render','--input',input,'--out',input,'--format','html']})).exitCode,4,'no self-overwrite');
  assert.equal((await runGuard({argv:['report','render','--input',input,'--out',path.join(tmp,'new.html')]})).exitCode,2,'format must be explicit');
  assert.equal((await runGuard({argv:['report','render','--help']})).exitCode,0);
  const utf16=path.join(tmp,'utf16.json');fs.writeFileSync(utf16,Buffer.from('\ufeff'+source.stdout,'utf16le'));
  assert.equal((await runGuard({argv:['report','render','--input',utf16,'--out',path.join(tmp,'bad.html'),'--format','html']})).exitCode,4);
  assert.equal(fs.existsSync(path.join(tmp,'bad.html')),false);
  const invalid=path.join(tmp,'unsafe.json');fs.writeFileSync(invalid,JSON.stringify(bad));
  assert.equal((await runGuard({argv:['report','render','--input',invalid,'--out',path.join(tmp,'unsafe.html'),'--format','html']})).exitCode,4);
  assert.equal(fs.existsSync(path.join(tmp,'unsafe.html')),false);
} finally {fs.rmSync(tmp,{recursive:true,force:true});}
console.log('PASS: English offline role-based HTML report (deterministic, safe escaping, bounded CLI, no input mutation).');
